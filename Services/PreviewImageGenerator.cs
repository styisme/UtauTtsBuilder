namespace UtauTtsBuilder.Services;

public static class PreviewImageGenerator
{
    /// <summary>
    /// 生成一张简单的预览 PNG：白底 + 声库名 + 音节数 + 日期
    /// </summary>
    public static async Task<string?> GenerateAsync(
        string outputDir, string name, int wavCount, string? iconPath)
    {
        try
        {
            const int W = 512, H = 320;

            using var bmp = new global::Android.Graphics.Bitmap(W, H);
            using var canvas = new global::Android.Graphics.Canvas(bmp);
            canvas.DrawColor(global::Android.Graphics.Color.ParseColor("#FEF7FF"));

            // 顶部色条
            using var barPaint = new global::Android.Graphics.Paint
            {
                Color = global::Android.Graphics.Color.ParseColor("#512BD4")
            };
            canvas.DrawRect(0, 0, W, 60, barPaint);

            // 图标
            int iconSize = 100;
            int iconX = 32, iconY = 90;
            if (!string.IsNullOrEmpty(iconPath) && File.Exists(iconPath))
            {
                try
                {
                    using var iconBmp = global::Android.Graphics.BitmapFactory.DecodeFile(iconPath);
                    if (iconBmp != null)
                    {
                        var dst = new global::Android.Graphics.Rect(iconX, iconY,
                            iconX + iconSize, iconY + iconSize);
                        canvas.DrawBitmap(iconBmp, null, dst, null);
                    }
                }
                catch { }
            }

            // 名称
            using var namePaint = new global::Android.Graphics.Paint
            {
                Color = global::Android.Graphics.Color.ParseColor("#1D1B20"),
                TextSize = 42,
                FakeBoldText = true,
                AntiAlias = true
            };
            canvas.DrawText(name, iconX + iconSize + 24, iconY + 50, namePaint);

            // 统计
            using var statPaint = new global::Android.Graphics.Paint
            {
                Color = global::Android.Graphics.Color.ParseColor("#49454F"),
                TextSize = 24,
                AntiAlias = true
            };
            canvas.DrawText($"{wavCount} syllables", iconX + iconSize + 24,
                iconY + 90, statPaint);

            // 底部说明
            using var footPaint = new global::Android.Graphics.Paint
            {
                Color = global::Android.Graphics.Color.ParseColor("#79747E"),
                TextSize = 18,
                AntiAlias = true
            };
            canvas.DrawText("Generated by UtauTtsBuilder",
                iconX, H - 40, footPaint);
            canvas.DrawText(DateTime.Now.ToString("yyyy-MM-dd"),
                W - 160, H - 40, footPaint);

            var path = Path.Combine(outputDir, "preview.png");
            using var fs = File.Create(path);
            bmp.Compress(global::Android.Graphics.Bitmap.CompressFormat.Png!, 100, fs);
            await fs.FlushAsync();
            return path;
        }
        catch
        {
            return null;
        }
    }
}
