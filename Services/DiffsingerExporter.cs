using System.IO.Compression;
using System.Text;

namespace UtauTtsBuilder.Services;

public static class DiffsingerExporter
{
    public static async Task<string> ExportAsync(string voicebankDir, string vbName)
    {
        var tmpDir = Path.Combine(FileSystem.CacheDirectory, "ds_export_" + Guid.NewGuid().ToString("N"));
        var rawDir = Path.Combine(tmpDir, "raw");
        Directory.CreateDirectory(rawDir);

        var wavs = Directory.GetFiles(voicebankDir, "*.wav");
        if (wavs.Length == 0)
            throw new Exception("No WAV files found in voicebank.");

        var transcriptions = new StringBuilder();

        foreach (var wav in wavs)
        {
            var fileName = Path.GetFileName(wav);
            var nameNoExt = Path.GetFileNameWithoutExtension(wav);
            
            // 复制 WAV
            File.Copy(wav, Path.Combine(rawDir, fileName), true);

            // 生成简单的音素序列 (启发式转写)
            var phonemes = GuessPhonemes(nameNoExt);
            
            // 写入 .lab 文件 (MFA/DiffSinger 兼容格式)
            File.WriteAllText(Path.Combine(rawDir, nameNoExt + ".lab"), phonemes, Encoding.UTF8);
            
            transcriptions.AppendLine($"raw/{fileName}|{phonemes}");
        }

        File.WriteAllText(Path.Combine(tmpDir, "transcriptions.txt"), transcriptions.ToString(), Encoding.UTF8);
        File.WriteAllText(Path.Combine(tmpDir, "README.txt"), 
            "DiffSinger / MFA Dataset generated by UtauTtsBuilder\n" +
            "1. Use Montreal Forced Aligner (MFA) to get TextGrids.\n" +
            "2. Convert TextGrids to DiffSinger format.\n" +
            "3. Train your model.", Encoding.UTF8);

        var zipPath = Path.Combine(FileSystem.CacheDirectory, $"{vbName}_DiffSinger_Dataset.zip");
        if (File.Exists(zipPath)) File.Delete(zipPath);
        ZipFile.CreateFromDirectory(tmpDir, zipPath);
        
        try { Directory.Delete(tmpDir, true); } catch { }

        return zipPath;
    }

    private static string GuessPhonemes(string name)
    {
        var vowels = new[] { 'a', 'i', 'u', 'e', 'o' };
        var lower = name.ToLowerInvariant();
        
        if (lower.Length == 1 && vowels.Contains(lower[0]))
            return lower;

        if (lower == "tsu") return "ts u";
        if (lower == "chi") return "ch i";
        if (lower == "shi") return "sh i";
        if (lower == "fu") return "f u";
        
        int vIndex = -1;
        for (int i = lower.Length - 1; i >= 0; i--)
        {
            if (vowels.Contains(lower[i])) { vIndex = i; break; }
        }

        if (vIndex > 0 && vIndex < lower.Length)
        {
            var cons = lower.Substring(0, vIndex);
            var vow = lower.Substring(vIndex);
            return $"{cons} {vow}";
        }

        return lower;
    }
}
