using System.IO.Compression;
using System.Text;

namespace UtauTtsBuilder.Services;

public static class DiffsingerExporter
{
    public class ExportOptions
    {
        public bool ExtractF0 { get; set; } = true;
        public bool ExtractEnergy { get; set; } = true;
        public bool DataAugmentation { get; set; } = true;
        public bool GenerateConfig { get; set; } = true;
    }

    public static async Task<string> ExportAsync(
        string voicebankDir, 
        string vbName, 
        ExportOptions options,
        IProgress<string> progress)
    {
        var tmpDir = Path.Combine(FileSystem.CacheDirectory, "ds_export_" + Guid.NewGuid().ToString("N"));
        var rawDir = Path.Combine(tmpDir, "raw");
        Directory.CreateDirectory(rawDir);

        var wavs = Directory.GetFiles(voicebankDir, "*.wav");
        if (wavs.Length == 0) throw new Exception("No WAV files found.");

        var durBuilder = new StringBuilder();
        var f0Builder = new StringBuilder();
        var energyBuilder = new StringBuilder();
        var transcriptions = new StringBuilder();

        int count = 0;
        foreach (var wav in wavs)
        {
            count++;
            var fileName = Path.GetFileName(wav);
            var nameNoExt = Path.GetFileNameWithoutExtension(wav);
            progress.Report($"Processing [{count}/{wavs.Length}] {fileName}");

            File.Copy(wav, Path.Combine(rawDir, fileName), true);

            var phonemes = GuessPhonemes(nameNoExt);
            transcriptions.AppendLine($"raw/{fileName}|{phonemes}");

            var info = WavProcessor.ReadWav(wav);
            var samples = WavProcessor.DecodeToFloat(info.RawData, info.BitsPerSample, info.Channels);
            var durMs = WavProcessor.GetDurationMs(wav);

            // 1. 时长切分
            var (consDur, vowDur) = GuessDurations(wav, voicebankDir, nameNoExt, durMs);
            if (phonemes.Contains(' '))
            {
                var parts = phonemes.Split(' ');
                durBuilder.AppendLine($"{nameNoExt}.wav|{consDur:F0} {vowDur:F0}");
            }
            else
            {
                durBuilder.AppendLine($"{nameNoExt}.wav|{durMs:F0}");
            }

            // 2. 特征提取
            if (options.ExtractF0)
            {
                var f0Points = ExtractF0(samples, info.SampleRate, 10);
                f0Builder.AppendLine($"{nameNoExt}.wav={string.Join(",", f0Points)}");
            }

            if (options.ExtractEnergy)
            {
                var energyPoints = ExtractEnergy(samples, info.SampleRate, 10);
                energyBuilder.AppendLine($"{nameNoExt}.wav={string.Join(",", energyPoints)}");
            }

            // 3. 数据增强 (生成变调版本)
            if (options.DataAugmentation)
            {
                var augName = nameNoExt + "_aug";
                var augPath = Path.Combine(rawDir, augName + ".wav");
                // 简单重采样变调 (+2 半音)
                var augSamples = ResampleForPitch(samples, 1.122f); 
                WavProcessor.WriteWav16(augPath, augSamples, info.SampleRate, 1);
                
                transcriptions.AppendLine($"raw/{augName}.wav|{phonemes}");
                durBuilder.AppendLine($"{augName}.wav|{consDur:F0} {vowDur:F0}");
                
                if (options.ExtractF0) 
                {
                    var augF0 = ExtractF0(augSamples, info.SampleRate, 10);
                    f0Builder.AppendLine($"{augName}.wav={string.Join(",", augF0)}");
                }
                if (options.ExtractEnergy)
                {
                    var augEnergy = ExtractEnergy(augSamples, info.SampleRate, 10);
                    energyBuilder.AppendLine($"{augName}.wav={string.Join(",", augEnergy)}");
                }
            }
        }

        progress.Report("Writing dataset files...");
        File.WriteAllText(Path.Combine(tmpDir, "transcriptions.txt"), transcriptions.ToString(), Encoding.UTF8);
        File.WriteAllText(Path.Combine(tmpDir, "ph_durs.txt"), durBuilder.ToString(), Encoding.UTF8);
        
        if (options.ExtractF0)
            File.WriteAllText(Path.Combine(tmpDir, "f0.txt"), f0Builder.ToString(), Encoding.UTF8);
        
        if (options.ExtractEnergy)
            File.WriteAllText(Path.Combine(tmpDir, "energy.txt"), energyBuilder.ToString(), Encoding.UTF8);

        // 4. 生成 Config 配置
        if (options.GenerateConfig)
        {
            var config = $@"# DiffSinger Configuration generated by UtauTtsBuilder
raw_data_dir: raw
binary_data_dir: binary
work_dir: checkpoints/{vbName}

sample_rate: 44100
hop_size: 512
fft_size: 2048
win_size: 2048

f0_min: 60
f0_max: 1000

# Dataset split
test_prefixes: []
val_split: 0.1

# Model
backbone_type: 'lynxnet'
";
            File.WriteAllText(Path.Combine(tmpDir, "config.yaml"), config, Encoding.UTF8);
        }

        File.WriteAllText(Path.Combine(tmpDir, "README.txt"), 
            "DiffSinger Dataset generated by UtauTtsBuilder\n" +
            "1. Run pre-processing scripts from DiffSinger repo.\n" +
            "2. Train your model using the generated config.yaml.", Encoding.UTF8);

        progress.Report("Compressing ZIP...");
        var zipPath = Path.Combine(FileSystem.CacheDirectory, $"{vbName}_DiffSinger_Max.zip");
        if (File.Exists(zipPath)) File.Delete(zipPath);
        ZipFile.CreateFromDirectory(tmpDir, zipPath);
        
        try { Directory.Delete(tmpDir, true); } catch { }
        return zipPath;
    }

    private static float[] ResampleForPitch(float[] samples, float ratio)
    {
        // 变调：改变播放速度 (简单的线性插值)
        int newLength = (int)(samples.Length / ratio);
        var result = new float[newLength];
        for (int i = 0; i < newLength; i++)
        {
            float srcPos = i * ratio;
            int i0 = (int)srcPos;
            int i1 = Math.Min(i0 + 1, samples.Length - 1);
            float frac = srcPos - i0;
            result[i] = samples[i0] * (1 - frac) + samples[i1] * frac;
        }
        return result;
    }

    private static (double ConsDur, double VowDur) GuessDurations(string wavPath, string voicebankDir, string name, double totalMs)
    {
        var otoPath = Path.Combine(voicebankDir, "oto.ini");
        if (File.Exists(otoPath))
        {
            System.Text.Encoding.RegisterProvider(System.Text.CodePagesEncodingProvider.Instance);
            var lines = File.ReadAllLines(otoPath, System.Text.Encoding.GetEncoding("shift_jis"));
            foreach (var line in lines)
            {
                if (line.StartsWith(name + ".wav="))
                {
                    var parts = line.Split('=')[1].Split(',');
                    if (parts.Length >= 3 && double.TryParse(parts[2], out double consonant))
                        return (consonant, totalMs - consonant);
                }
            }
        }
        return (totalMs * 0.2, totalMs * 0.8);
    }

    private static List<string> ExtractEnergy(float[] samples, int sr, int hopMs)
    {
        int hop = (int)(sr * (hopMs / 1000.0));
        int window = (int)(sr * 0.04);
        var list = new List<string>();

        for (int i = 0; i <= samples.Length - window; i += hop)
        {
            float sumSq = 0;
            for (int j = 0; j < window; j++) sumSq += samples[i + j] * samples[i + j];
            float rms = (float)Math.Sqrt(sumSq / window);
            list.Add(rms.ToString("F4"));
        }
        return list;
    }

    private static List<string> ExtractF0(float[] samples, int sr, int hopMs)
    {
        int hop = (int)(sr * (hopMs / 1000.0));
        int window = (int)(sr * 0.04);
        int minLag = sr / 800;
        int maxLag = sr / 80;
        var f0List = new List<string>();

        for (int i = 0; i <= samples.Length - window; i += hop)
        {
            float bestCorr = 0; int bestLag = 0;
            for (int lag = minLag; lag <= maxLag && lag < window; lag++)
            {
                float sum = 0;
                for (int j = 0; j < window - lag; j++) sum += samples[i + j] * samples[i + j + lag];
                if (sum > bestCorr) { bestCorr = sum; bestLag = lag; }
            }
            if (bestLag > 0 && bestCorr > 0.01f)
                f0List.Add($"{(float)sr / bestLag:F1}");
            else
                f0List.Add("0");
        }

        // 平滑
        for (int i = 1; i < f0List.Count - 1; i++)
        {
            if (f0List[i] != "0" && f0List[i - 1] != "0" && f0List[i + 1] != "0")
            {
                float p = float.Parse(f0List[i - 1]), c = float.Parse(f0List[i]), n = float.Parse(f0List[i + 1]);
                if (Math.Abs(c - p) > 50 && Math.Abs(c - n) > 50) f0List[i] = ((p + n) / 2).ToString("F1");
            }
        }
        return f0List;
    }

    private static string GuessPhonemes(string name)
    {
        var vowels = new[] { 'a', 'i', 'u', 'e', 'o' };
        var lower = name.ToLowerInvariant().Replace("_aug", "");
        if (lower.Length == 1 && vowels.Contains(lower[0])) return lower;
        if (lower == "tsu") return "ts u";
        if (lower == "chi") return "ch i";
        if (lower == "shi") return "sh i";
        if (lower == "fu") return "f u";
        int vIndex = -1;
        for (int i = lower.Length - 1; i >= 0; i--)
            if (vowels.Contains(lower[i])) { vIndex = i; break; }
        if (vIndex > 0 && vIndex < lower.Length)
            return $"{lower.Substring(0, vIndex)} {lower.Substring(vIndex)}";
        return lower;
    }
}
