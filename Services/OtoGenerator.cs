using System.Globalization;
using System.Text;

namespace UtauTtsBuilder.Services;

public class OtoEntry
{
    public string FileName { get; set; } = string.Empty;
    public string Alias { get; set; } = string.Empty;
    public double Offset { get; set; }
    public double Consonant { get; set; }
    public double Cutoff { get; set; }
    public double Preutterance { get; set; }
    public double Overlap { get; set; }

    public string ToOtoLine()
    {
        var ci = CultureInfo.InvariantCulture;
        return string.Format(ci,
            "{0}={1},{2:F0},{3:F0},{4:F0},{5:F0},{6:F0}",
            FileName, Alias, Offset, Consonant, Cutoff, Preutterance, Overlap);
    }
}

public static class OtoGenerator
{
    public static OtoEntry GenerateEntry(string wavPath, string alias)
    {
        double duration = WavProcessor.GetDurationMs(wavPath);

        double offset = 30;
        double consonant = Math.Max(80, duration * 0.35);
        double cutoff = -Math.Max(50, duration * 0.2);
        double preutterance = Math.Max(30, consonant - 40);
        double overlap = Math.Max(15, preutterance * 0.5);

        if (alias.Length == 1 ||
            alias == "ん" ||
            alias == "啊" || alias == "哦" || alias == "鹅" ||
            alias == "衣" || alias == "乌" || alias == "鱼")
        {
            consonant = Math.Max(50, duration * 0.15);
            preutterance = Math.Max(20, consonant - 20);
            overlap = Math.Max(10, preutterance * 0.5);
        }

        return new OtoEntry
        {
            FileName = Path.GetFileName(wavPath),
            Alias = alias,
            Offset = Math.Round(offset),
            Consonant = Math.Round(consonant),
            Cutoff = Math.Round(cutoff),
            Preutterance = Math.Round(preutterance),
            Overlap = Math.Round(overlap)
        };
    }

    public static async Task WriteOtoIniAsync(
        IEnumerable<OtoEntry> entries, string outputPath)
    {
        var sjis = GetSjisWithFallback();
        var sb = new StringBuilder();
        foreach (var e in entries)
            sb.AppendLine(e.ToOtoLine());
        await File.WriteAllTextAsync(outputPath, sb.ToString(), sjis);
    }

    // 原版 UTAU：character.txt（Shift-JIS，字段 name / image / author）
    public static async Task WriteCharacterTxtAsync(
        string dir,
        string name,
        string? iconFileName = null,
        string? author = null)
    {
        var sjis = GetSjisWithFallback();

        var sb = new StringBuilder();
        sb.Append("name=").AppendLine(name);
        if (!string.IsNullOrEmpty(iconFileName))
            sb.Append("image=").AppendLine(iconFileName);
        sb.Append("author=").AppendLine(
            string.IsNullOrEmpty(author) ? "Auto-generated by UtauTtsBuilder" : author);

        await File.WriteAllTextAsync(
            Path.Combine(dir, "character.txt"), sb.ToString(), sjis);
    }

    // OpenUtau：character.yaml（UTF-8，含立绘）
    public static async Task WriteCharacterYamlAsync(
        string dir,
        string name,
        string? iconFileName = null,
        string? portraitFileName = null,
        string? author = null,
        string textEncoding = "shift_jis")
    {
        var sb = new StringBuilder();
        sb.Append("name: ").AppendLine(YamlEscape(name));

        if (!string.IsNullOrEmpty(iconFileName))
            sb.Append("image: ").AppendLine(YamlEscape(iconFileName));

        if (!string.IsNullOrEmpty(portraitFileName))
        {
            sb.Append("portrait: ").AppendLine(YamlEscape(portraitFileName));
            sb.AppendLine("portrait_opacity: 0.67");
            sb.AppendLine("portrait_height: 720");
            sb.AppendLine("portrait_x_offset: 0");
            sb.AppendLine("portrait_y_offset: 0");
        }

        sb.Append("author: ").AppendLine(
            YamlEscape(string.IsNullOrEmpty(author)
                ? "Auto-generated by UtauTtsBuilder"
                : author));

        sb.Append("text_file_encoding: ").AppendLine(textEncoding);
        sb.AppendLine("default_phonemizer: OpenUtau.Core.DefaultPhonemizer");

        char qq = (char)34;
        sb.AppendLine("subbanks:");
        sb.AppendLine("- color: " + qq + qq);
        sb.AppendLine("  prefix: " + qq + qq);
        sb.AppendLine("  suffix: " + qq + qq);
        sb.AppendLine("  tone_ranges:");
        sb.AppendLine("  - C1-B7");

        var utf8 = new UTF8Encoding(false);
        await File.WriteAllTextAsync(
            Path.Combine(dir, "character.yaml"), sb.ToString(), utf8);
    }

    private static string YamlEscape(string s)
    {
        if (string.IsNullOrEmpty(s)) return new string((char)34, 2);
        char b = (char)92;
        return q + s.Replace(q.ToString(), b + q.ToString()) + q;
    }

    private static Encoding GetSjisWithFallback()
    {
        Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
        try
        {
            return Encoding.GetEncoding("shift_jis",
                new EncoderReplacementFallback("?"),
                new DecoderReplacementFallback("?"));
        }
        catch
        {
            return Encoding.UTF8;
        }
    }
}
